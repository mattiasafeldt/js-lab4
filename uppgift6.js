"use strict";

function calculateArea(width, height) {
    return width * height;
}
console.log("Arean är " + calculateArea(4, 5)); // När arean är 20
console.log("Arean är " + calculateArea(6, 7)); // När arean är 42
console.log("Arean är " + calculateArea(10, 10)); // När arean är 100